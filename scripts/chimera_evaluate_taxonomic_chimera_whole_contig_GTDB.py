#!/usr/bin/env python3
"""Whole-contig GTDB taxonomic-chimera scan using bounded adaptive gene blocks.

Every inter-gene boundary on each long-read assembly contig is evaluated independently at
domain, phylum, class and order. On each side, the evaluator searches outward
through at most a bounded number of immediately adjacent predicted genes.
Unclassified genes are skipped for taxonomic voting but still consume the
search budget, so distant classified genes cannot be pulled into a local block.
Up to a target number of classified genes are selected, with a configurable
minimum required for that side to be evaluable. Dominance is calculated only
among the selected classified genes.

With the default settings, at most 10 predicted genes are searched per side,
up to 5 classified genes are selected, at least 4 classified genes are required,
and the dominant taxon must account for at least 80% of the selected classified
genes. A qualifying transition requires different dominant taxa on the two
sides at the same rank. No fixed base-pair taxonomy window is used.

A qualifying taxonomic transition is a candidate chimeric junction only.
This module generates taxonomic-transition candidates and local GC/depth context.
Final structural-chimera calls are assigned downstream by direct HiFi continuity
validation; the legacy Taxonomic_chimera fields written here are intermediate-only.

For MAG-associated contigs, the MAG GTDB-Tk lineage is also reported at the transition
rank so the left and right taxonomic blocks can be annotated as MAG-consistent or
MAG-discordant. Non-MAG contigs receive MAG_ID=NA and NA for these MAG-specific fields.
This directionality is descriptive and does not alter the taxonomic-shift call.

GC content and HiFi depth are measured over the genomic span of the selected
classified genes used for taxonomic evaluation. HiFi depth uses primary
alignments without a MAPQ filter from the complete co-assembly generated by
the assembler that produced each contig. GC and depth are descriptive measurements only and do not create or
reject a taxonomic-chimera call.
"""

